const contentItemToSeedMyth = (item: ContentItem): MythEntry => ({
  id: item.id,
  name: item.title.ar,
  latinName: item.title.en,
  category: item.legacyCategory ?? 'personalities',
  typeLabel:
    item.type === 'story'
      ? 'قصة'
      : item.type === 'myth'
      ? 'أسطورة'
      : item.type === 'cosmology'
      ? 'كوسمولوجيا'
      : 'فلكلور',
  heroImage: item.image,
  summary: item.summary.ar,
  body: item.text.ar,
  sources: [
    {
      title: item.source.title.ar,
      author: item.source.author.ar,
      year: item.source.year || '',
    },
  ],
  timeline: [
    {
      era: 'جاهلية',
      note: item.summary.ar,
    },
  ],
  region: item.region.label.ar,
  related: item.creatureIds
    ? item.creatureIds
        .map((cid) => CREATURES_CATALOG.find((c) => c.id === cid)?.legacyMythId)
        .filter((mid): mid is string => Boolean(mid && mid !== item.id))
    : [],
  tags: item.tags as MythEntry['tags'],
});

const PUBLIC_DOMAIN_MYTHS: MythEntry[] = PUBLIC_DOMAIN_STORIES.map(contentItemToSeedMyth);

