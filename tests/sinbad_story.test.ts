import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { getDeepStory, hasDeepStory } from '../src/data/storyTypes';
import { countWords } from '../src/utils/readingTime';

const EXPECTED_SOURCE = 'ألف ليلة وليلة — حكاية السندباد البحري';
const EXPECTED_EVIDENCE_LABEL = 'خيال أدبي';

const EXPECTED_CH0_TITLE = 'الإطار: السندباد الفقير والسندباد الغني';
const EXPECTED_CH0_TEXT = `في بغدادَ، في أيام هارون الرشيد، كان حمّالٌ اسمه السندباد يحمل الأثقال على رأسه من سوقٍ إلى سوق، ويعرقُ من الفجر إلى الليل ولا يجمع إلا قوتَ يومه. وفي يومٍ شديد الحرّ جلس يستريح عند باب دارٍ واسعة، فرأى عليها بساطاً وخدماً وروائحَ طيبٍ وماءً مرشوشاً. فرفع رأسه إلى السماء وقال:

يا خالقَ كلِّ شيءٍ ما أبعدَ ما بين حظّي وحظّ صاحب هذه الدار! أنت قسمتَ الأرزاق، فجعلتَ هذا في نعيمٍ وجعلتَني في تعب؛ هذا يملكُ الدورَ والبساتين، وأنا لا أملكُ إلا حملاً على رأسي وقدمين متشقّقتين.

فسمعه صاحب الدار، وكان اسمه السندباد أيضاً، تاجراً قد طاف البحارَ السبعة. فأرسل إليه رسولاً وأدخله، وأجلسه في صدر المجلس، وقدّم له طعاماً لم يرَ مثلَه. ثم قال له: اعلم يا هذا أني لم أصل إلى ما ترى بالراحة ولا بالميراث، بل بسبع رحلاتٍ أهوالُها تشيبُ الرأس، لو كُتبت بالإبر على مآقي العيون لكانت عبرةً لمن يعتبر. ثم قال: اجلس عندي كل يومٍ إلى أن أقصّ عليك رحلةً رحلة، ولك في كل يومٍ مئةُ دينار.

فقال الحمّال: ومن أين لي هذا الحظ؟ فقال التاجر: من صبرك على السماع، ومن صبري على الحكاية.

وهكذا انعقد العقد: حمّالٌ يسمع، وتاجرٌ يحكي، ومئةُ دينارٍ ثمنُ كل حكاية. فالقصة هنا ليست تسليةً فقط، بل أجرٌ على الصبر، وعقدٌ بين من يملك التجربة ومن يملك الانتباه. ومن هنا يفهم صانع المحتوى أن السندباد يروي ليُعلّم، وأن كل رحلةٍ درسٌ في النجاة، وأن الحكاية عملةٌ تُدفع لمن يجلس إلى آخرها.

وفي كل ليلةٍ كان التاجر يبدأ بجملةٍ واحدة: «اعلم يا أخي أني…» ثم يفتح باباً من أبواب البحر. وفي كل صباحٍ يدفع للحمّال مئة دينار ويقول: هذه أُجرة يومك، وغداً رحلةٌ أخرى. فالسندباد الغني يشتري بصبر الحمّال وقتَه، والحمّال يشتري بحكايات التاجر أملَه.`;

const EXPECTED_CH1_TITLE = 'الرحلة الأولى: جزيرة الحوت والملك والبحر';
const EXPECTED_CH1_TEXT = `قال السندباد: اعلم يا أخي أن أبي مات وترك لي مالاً كثيراً، فأكلته في لهوٍ وشربٍ وصحبةٍ حتى لم يبقَ منه شيء. فلما أفقتُ ونظرتُ إلى يديّ الفارغتين قلت: أرجع إلى تجارة أبي، فالرجلُ لا يُصلح ما أفسده إلا العملُ الذي أفسده. فبعتُ ما بقي من ثيابي وأثاثي واشتريتُ بضاعةً، ونزلتُ إلى البصرة وركبتُ سفينةً مع تجارٍ يخرجون إلى الجزر.

فسرنا أياماً وليالي، حتى رسونا على جزيرةٍ كأنها روضة: أشجارٌ وأنهارٌ وطيورٌ وثمار. فنزل الناس يستطيبون، وأوقدوا ناراً لطبخٍ. فلما اشتعلت النار تحركت الجزيرةُ واهتزّت! فإذا هي حوتٌ عظيمٌ نائمٌ على وجه الماء، قد نبت عليه الرملُ والشجرُ من طول سكونه، حتى حسبَه الناسُ أرضاً. فلما أحسّ الحرارة غاص في البحر، وبقي الناس بين غريقٍ ونجٍ. وكنتُ ممن قفز إلى الماء، فتعلقتُ بوعاءٍ خشبيٍّ كبيرٍ من أوعية السفينة، فحملني الموجُ يومين وليلةً حتى ألقاني على جزيرةٍ عالية.

وهنا الدرس الأول: لا تثق بأرضٍ لا تعرف أصلها. فالجزيرة التي ليست جزيرةً تُغرق من يبني عليها نارَه. والنارُ هي التي كشفت الحقيقة: ما كان يظنّه الناسُ مستقراً كان كائناً حياً نائماً. ومن هنا يفهم صانع الألعاب أن «الأرض الآمنة» قد تكون وحشاً نائماً، وأن أول فعلٍ يكشفه.

فلما أخرجني الموجُ إلى الجزيرة رأيتُ شيخاً يربط فرساً على شاطئ البحر، فسألته، فقال: هذه فرسُ الملك، نربطها هنا ليخرج إليها حصانُ البحر فيحمل منها خيلاً لا تُرى مثلها. فلما سمعتُ كلامه إذا بحصانٍ أسودَ يخرج من الماء ويرعد، فهمّ أن يعلو الفرس، فصرخ الشيخ، فجاء السّواسُ من كل جانبٍ فطردوه. فلما علم الملكُ بما فعلتُ من إنقاذ فرسه أعجب بي، وجعلني أمينَ مرفئه وكاتبَ شحنه، وأدخلني في نعمته.

فصرتُ أجلس في مجلس الملك وأسمع أخبارَ التجار، حتى رست يوماً سفينةٌ، فقال ربانها: كنا فقدنا تاجراً اسمه السندباد في أول السفر، وله بضاعةٌ معنا لم نسلّمها لأحد. فقلتُ: أنا السندباد! فقال: ومن يصدّقك؟ فذكرتُ له علاماتي وعلامات بضاعتي، فسلّم إليّ بضاعتي سالمة. فبعتُها وربحتُ فيها ربحاً كثيراً، واشتريتُ غيرها، وعدتُ إلى بغداد أغنى مما كنت.

وهنا الدرس الثاني: تمسّك بأداة النجاة لا بالسفينة الغارقة. فالوعاء الخشبي الذي أنقذني لم يكن سفينةً ولا شراعاً، بل شيئاً صغيراً طافياً. وفي كل بحرٍ أهوالُه، يكون النجاةُ لمن تعلّق بأبسط ما يطفو، لا لمن تشبّث بما يغرق.

ثم عدتُ إلى بغداد، وأعطيتُ الحمّال مئة دينار، وقلت: هذه أُجرة يومك، وغداً أقصّ عليك الثانية، ففيها طائرٌ يحمل الفيل، وواديٌ حافتُه ألماسٌ وقاعُه ثعابين.`;

describe('Sinbad batch 1 (frame + First Voyage) in stories.json', () => {
  it('merges chapter 0 (frame) and chapter 1 (First Voyage) verbatim with exact source and evidenceLabel', () => {
    assert.equal(hasDeepStory('sinbad'), true);
    const story = getDeepStory('sinbad');
    assert.ok(story, 'sinbad story must exist');
    assert.equal(story.source, EXPECTED_SOURCE);
    assert.equal(story.chaptersCount, 2);
    assert.ok(Array.isArray(story.chapters) && story.chapters.length === 2);

    const [ch0, ch1] = story.chapters;

    assert.equal(ch0.title, EXPECTED_CH0_TITLE);
    assert.equal(ch0.evidenceLabel, EXPECTED_EVIDENCE_LABEL);
    assert.equal(ch0.source, EXPECTED_SOURCE);
    assert.equal(ch0.text, EXPECTED_CH0_TEXT);

    assert.equal(ch1.title, EXPECTED_CH1_TITLE);
    assert.equal(ch1.evidenceLabel, EXPECTED_EVIDENCE_LABEL);
    assert.equal(ch1.source, EXPECTED_SOURCE);
    assert.equal(ch1.text, EXPECTED_CH1_TEXT);
  });

  it('sets accurate word counts, reading times at 180 WPM, and batch 1 metadata arrays', () => {
    const story = getDeepStory('sinbad')!;
    const [ch0, ch1] = story.chapters!;

    const ch0Words = countWords(ch0.title) + countWords(ch0.text);
    const ch1Words = countWords(ch1.title) + countWords(ch1.text);

    assert.equal(ch0.wordCount, ch0Words);
    assert.equal(ch0.estimatedReadingMinutes, Math.max(1, Math.ceil(ch0Words / 180)));

    assert.equal(ch1.wordCount, ch1Words);
    assert.equal(ch1.estimatedReadingMinutes, Math.max(1, Math.ceil(ch1Words / 180)));

    assert.equal(story.totalWords, ch0Words + ch1Words);
    assert.equal(story.estimatedReadingMinutes, Math.max(1, Math.ceil((ch0Words + ch1Words) / 180)));

    assert.deepEqual(story.motifs, [
      'الجزيرة التي ليست جزيرة',
      'الوعاء الطافي',
      'حصان البحر',
      'استرداد البضاعة',
    ]);
    assert.deepEqual(story.themes, [
      'النجاة بأبسط أداة',
      'لا تثق بأرض لا تعرف أصلها',
      'الحكاية عملة',
    ]);
    assert.deepEqual(story.cast, [
      'السندباد التاجر',
      'السندباد الحمّال',
      'الملك',
      'ربان السفينة',
      'حصان البحر',
    ]);
  });
});
